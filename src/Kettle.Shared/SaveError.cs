public static class SaveErrors
{
    private const string Key = "Kettle.SaveError";
    public static T Tag<T>(T error, SaveErrorCode code, string? detail = null, SaveError? cause = null, string? prefixCode = null) where T : Exception
    {
        error.Data[Key] = new SaveError(code.ToString(), detail, cause, prefixCode);
        return error;
    }
    public static SaveError Describe(Exception error) => error.Data[Key] as SaveError ?? new("", error.Message);
}
